-- Inventory Management System: Oracle 21c
-- Run only if these tables do not already exist.

CREATE TABLE suppliers (
    supplier_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR2(100) NOT NULL,
    phone         VARCHAR2(20),
    email         VARCHAR2(120) UNIQUE
);

CREATE TABLE categories (
    category_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR2(80) NOT NULL UNIQUE
);

CREATE TABLE products (
    product_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name      VARCHAR2(120) NOT NULL,
    category_id       NUMBER NOT NULL,
    supplier_id       NUMBER NOT NULL,
    unit_price        NUMBER(12,2) NOT NULL CHECK (unit_price >= 0),
    quantity_in_stock NUMBER DEFAULT 0 NOT NULL CHECK (quantity_in_stock >= 0),
    reorder_level     NUMBER DEFAULT 5 NOT NULL CHECK (reorder_level >= 0),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id)
        REFERENCES categories(category_id),
    CONSTRAINT fk_products_supplier FOREIGN KEY (supplier_id)
        REFERENCES suppliers(supplier_id)
);

CREATE TABLE purchases (
    purchase_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        NUMBER NOT NULL,
    quantity_purchased NUMBER NOT NULL CHECK (quantity_purchased > 0),
    purchase_date     DATE DEFAULT SYSDATE NOT NULL,
    unit_cost         NUMBER(12,2) NOT NULL CHECK (unit_cost >= 0),
    CONSTRAINT fk_purchases_product FOREIGN KEY (product_id)
        REFERENCES products(product_id)
);

CREATE TABLE sales (
    sale_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    NUMBER NOT NULL,
    quantity_sold NUMBER NOT NULL CHECK (quantity_sold > 0),
    sale_date     DATE DEFAULT SYSDATE NOT NULL,
    selling_price NUMBER(12,2) NOT NULL CHECK (selling_price >= 0),
    CONSTRAINT fk_sales_product FOREIGN KEY (product_id)
        REFERENCES products(product_id)
);
